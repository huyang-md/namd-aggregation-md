"""One command from a packed structure to runnable NAMD inputs.

Runs the steps that need no chemistry judgement:
    ③ box from target concentration
    ④ Packmol packing
    ⑤ psfgen topology
    ⑥ VMD solvate + neutralize
    ⑦ NAMD .conf generation
    ⑧ pre-flight report

It stops and says what is missing when a tool is absent, rather than half-finishing.

    python pipeline.py --dir mycase --name mycase --ligand-pdb mol.pdb \
        --molecules 50 --target-conc-mM 50 --prod-ns 100
    python pipeline.py --dir mycase --skip-pack --skip-build     # resume from solvate
"""
from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from collections import Counter

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import namdlib  # noqa: E402
import scaffold  # noqa: E402

OK, SKIP, FAIL = "OK", "SKIP", "FAIL"


def say(mark, text):
    print(f"[{mark:4}] {text}", flush=True)


def find_tool(explicit, names):
    """Locate an executable: explicit path, then PATH, then common install roots.

    Set MD_TOOLS_DIR (pathsep-separated) to add your own search roots, e.g.
    ``MD_TOOLS_DIR=/opt/md-tools:/home/me/bin`` on Linux, or on Windows
    ``set MD_TOOLS_DIR=C:/tools;E:/more-tools`` (forward slashes avoid escapes).
    The walk is depth-bounded so pointing it at a large directory does not stall the run.
    """
    if explicit:
        return explicit if os.path.exists(explicit) else None
    for n in names:
        p = shutil.which(n)
        if p:
            return p

    roots = [p for p in os.environ.get("MD_TOOLS_DIR", "").split(os.pathsep) if p]
    if sys.platform.startswith("win"):
        for var in ("ProgramFiles", "ProgramFiles(x86)", "ProgramW6432"):
            v = os.environ.get(var)
            if v:
                roots.append(v)
    else:
        roots.extend(["/usr/local", "/opt", "/usr/bin"])

    wanted = {n.lower() for n in names}
    for root in roots:
        if not os.path.isdir(root):
            continue
        base_depth = root.rstrip(os.sep).count(os.sep)
        for dirpath, dirs, files in os.walk(root):
            if dirpath.count(os.sep) - base_depth >= 4:
                dirs[:] = []
            for f in files:
                if f.lower() in wanted:
                    return os.path.join(dirpath, f)
    return None


def run(cmd, cwd, logfile, timeout=3600, stdin_file=None):
    print("      $ " + " ".join(str(c) for c in cmd), flush=True)
    try:
        fin = open(stdin_file, "r", encoding="utf-8") if stdin_file else subprocess.DEVNULL
        with open(logfile, "w", encoding="utf-8", errors="replace") as fh:
            r = subprocess.run(cmd, cwd=cwd, stdin=fin, stdout=fh,
                               stderr=subprocess.STDOUT, timeout=timeout)
        if stdin_file:
            fin.close()
        tail = ""
        try:
            with open(logfile, encoding="utf-8", errors="replace") as fh:
                lines = [l for l in fh.read().splitlines() if l.strip()]
            tail = lines[-1][:120] if lines else ""
        except OSError:
            pass
        return r.returncode == 0, tail
    except FileNotFoundError:
        return False, "command not found"
    except subprocess.TimeoutExpired:
        return False, "timed out"


