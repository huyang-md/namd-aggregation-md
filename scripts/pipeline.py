def render_psfgen(work_dir, com_pdb, out_psf, out_pdb, cgenff_top, lig_rtf, resname):
    return f"""# generated by pipeline.py -- psfgen
package require psfgen
topology {{{cgenff_top}}}
topology {{{lig_rtf}}}
pdbalias residue {resname} lig
segment S {{ pdb {com_pdb} }}
coordpdb {com_pdb} S
guesscoord
writepsf {out_psf}
writepdb {out_pdb}
puts "PSFGEN_DONE"
exit
"""


def render_solvate(work_dir, proc_psf, proc_pdb, box, out_base):
    return f"""# generated by pipeline.py -- VMD solvate + neutralize
package require solvate
package require autoionize
solvate {proc_psf} {proc_pdb} -minmax {{{{0.0 0.0 0.0}} {{{box:.3f} {box:.3f} {box:.3f}}}}} -o {out_base}_solv
autoionize -psf {out_base}_solv.psf -pdb {out_base}_solv.pdb -o {out_base} -neutralize
puts "SOLVATE_DONE"
exit
"""


def check_ionized(directory, name):
    psf = os.path.join(directory, f"{name}.psf")
    if not os.path.exists(psf):
        return None
    natoms, atoms = namdlib.read_psf(psf)
    total = sum(a["charge"] for a in atoms)
    counts = Counter(a["resname"] for a in atoms)
    return dict(natoms=natoms, charge=total, counts=counts)


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--dir", required=True, help="case directory to build in")
    p.add_argument("--name", help="case name (default: directory name)")
    p.add_argument("--ligand-pdb", required=True, help="single-molecule pdb fed to Packmol")
    p.add_argument("--molecules", type=int, required=True)
    p.add_argument("--target-conc-mM", type=float, required=True)
    p.add_argument("--solvate-pad", type=float, default=8.0)
    p.add_argument("--packmol-seed", type=int, default=12345)
    p.add_argument("--resname", default="LIG", help="residue name in the ligand pdb")
    p.add_argument("--ligand-rtf", help="topology from CGenFF (default <dir>/lig/lig.rtf)")
    p.add_argument("--cgenff-top", help="top_all36_cgenff.rtf (default <dir>/toppar/...)")
    p.add_argument("--packmol")
    p.add_argument("--vmd")
    p.add_argument("--skip-pack", action="store_true", help="packed pdb already exists")
    p.add_argument("--skip-build", action="store_true", help="PSF already exists")
    p.add_argument("--skip-solvate", action="store_true", help="solvated system already exists")
    p.add_argument("--prod-ns", type=float, default=100.0)
    p.add_argument("--dcdfreq-ps", type=float, default=10.0)
    a = p.parse_args(argv)

    d = os.path.abspath(a.dir)
    os.makedirs(d, exist_ok=True)
    name = a.name or os.path.basename(d.rstrip("\\/"))
    log_dir = os.path.join(d, "_pipeline_logs")
    os.makedirs(log_dir, exist_ok=True)

    # ---- check inputs ---------------------------------------------------
    lig_pdb = os.path.join(d, a.ligand_pdb) if not os.path.isabs(a.ligand_pdb) else a.ligand_pdb
    if not os.path.exists(lig_pdb):
        say(FAIL, f"ligand pdb not found: {lig_pdb}")
        return 2

    lig_rtf = a.ligand_rtf or os.path.join(d, "lig", "lig.rtf")
    if not os.path.exists(lig_rtf):
        alt = os.path.join(d, "lig.rtf")
        lig_rtf = alt if os.path.exists(alt) else lig_rtf
    cgenff_top = a.cgenff_top or os.path.join(d, "toppar", "top_all36_cgenff.rtf")
    if not os.path.exists(cgenff_top):
        say(FAIL, f"cgenff topology not found: {cgenff_top}")
        say("", "  copy top_all36_cgenff.rtf into <dir>/toppar/ or pass --cgenff-top")
        return 2
    if not os.path.exists(lig_rtf):
        say(FAIL, f"ligand topology not found: {lig_rtf}")
        say("", "  generate it with CHARMM-GUI Ligand Reader (step 2 of docs/tutorial.md)")
        return 2

    n_lig_atoms = sum(1 for ln in open(lig_pdb, "r", errors="replace")
                      if ln.startswith(("ATOM", "HETATM")))
    say(OK, f"ligand: {os.path.basename(lig_pdb)} ({n_lig_atoms} atoms), "
            f"{a.molecules} copies at {a.target_conc_mM:g} mM")

    # ---- ③ box -----------------------------------------------------------
    side, vol = scaffold.box_for_concentration(a.molecules, a.target_conc_mM)
    inner = side - 2.0 * a.solvate_pad
    if inner <= 5.0:
        say(FAIL, f"final box {side:.1f} A leaves no room after {a.solvate_pad} A padding")
        return 2
    say(OK, f"box: final {side:.2f} A ({vol / 1000:,.0f} nm3), packing {inner:.2f} A")

    # ---- ④ Packmol -------------------------------------------------------
    com_pdb = f"{name}_com.pdb"
    if a.skip_pack:
        say(SKIP, f"packing (using existing {com_pdb})")
    else:
        packmol = find_tool(a.packmol, ["packmol.exe", "packmol"])
        wa_text, _ = scaffold.render_packmol(
            {"name": name, "ligand_pdb": a.ligand_pdb},
            a.molecules, side, a.solvate_pad, a.ligand_pdb, a.packmol_seed)
        with open(os.path.join(d, "wa.inp"), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(wa_text)
        if not packmol:
            say(FAIL, "packmol not found — wa.inp written, run it yourself:")
            say("", "      packmol < wa.inp      (or pass --packmol <path>)")
            say("", "      then re-run with --skip-pack")
            return 2
        ok, tail = run([packmol], d, os.path.join(log_dir, "packmol.log"),
                       stdin_file=os.path.join(d, "wa.inp"))
        say(OK if ok else FAIL, f"packmol: {tail}")
        if not ok and not os.path.exists(os.path.join(d, com_pdb)):
            return 2

    # ---- ⑤ psfgen --------------------------------------------------------
    proc_psf, proc_pdb = f"{name}_proc.psf", f"{name}_proc.pdb"
    if a.skip_build:
        say(SKIP, f"psfgen (using existing {proc_psf})")
    else:
        vmd = find_tool(a.vmd, ["vmd.exe", "vmd"])
        if not vmd:
            say(FAIL, "VMD not found; pass --vmd <path to vmd.exe>")
            return 2
        tcl = render_psfgen(d, com_pdb, proc_psf, proc_pdb, cgenff_top, lig_rtf, a.resname)
        with open(os.path.join(d, "build.tcl"), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(tcl)
        ok, tail = run([vmd, "-dispdev", "text", "-e", "build.tcl"], d,
                       os.path.join(log_dir, "psfgen.log"))
        got = os.path.exists(os.path.join(d, proc_psf))
        say(OK if got else FAIL, f"psfgen: {'wrote ' + proc_psf if got else tail}")
        if not got:
            return 2

    # ---- ⑥ solvate + neutralize -----------------------------------------
    # final files use the conventional names that scaffold.py expects
    final_psf, final_pdb = "ionized.psf", "ionized.pdb"
    if a.skip_solvate and os.path.exists(os.path.join(d, final_psf)):
        say(SKIP, f"solvate (using existing {final_psf})")
    else:
        vmd = find_tool(a.vmd, ["vmd.exe", "vmd"])
        if not vmd:
            say(FAIL, "VMD not found")
            return 2
        tcl = render_solvate(d, proc_psf, proc_pdb, side, name)
        with open(os.path.join(d, "solvate.tcl"), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(tcl)
        ok, tail = run([vmd, "-dispdev", "text", "-e", "solvate.tcl"], d,
                       os.path.join(log_dir, "solvate.log"))
        # autoionize writes <name>.psf / <name>.pdb
        got = os.path.exists(os.path.join(d, f"{name}.psf"))
        if got:
            os.replace(os.path.join(d, f"{name}.psf"), os.path.join(d, final_psf))
            os.replace(os.path.join(d, f"{name}.pdb"), os.path.join(d, final_pdb))
        say(OK if got else FAIL, f"solvate + neutralize: {tail}")
        if not got:
            return 2

    psf_path = os.path.join(d, final_psf)
    if os.path.exists(psf_path):
        natoms, atoms = namdlib.read_psf(psf_path)
        counts = Counter(a["resname"] for a in atoms)
        total = sum(a["charge"] for a in atoms)
        ions = {k: v for k, v in counts.items() if k.upper() in ("CLA", "SOD", "NA", "CL", "K")}
        say(OK if abs(total) < 1e-3 else FAIL,
            f"system: {natoms:,} atoms, net charge {total:+.4f}, ions {ions}")
        if abs(total) > 1e-3:
            say("", "  net charge is not zero; PME will misbehave — check the neutralize step")

    # ---- ⑦ conf + ⑧ preflight -------------------------------------------
    args = ["--dir", d, "--name", name, "--prod-ns", str(a.prod_ns),
            "--dcdfreq-ps", str(a.dcdfreq_ps), "--force"]
    if scaffold.main(args) != 0:
        say(FAIL, "scaffold failed")
        return 2
    say(OK, "NAMD .conf written")

    import preflight
    rc = preflight.main(["--dir", d])
    say(OK if rc == 0 else FAIL, "preflight " + ("passed" if rc == 0 else "reported FAIL items"))

    print("\nnext:")
    print(f"  namd2 {name}.conf > {name}.log          # copy the directory to the cluster")
    print(f"  & $py analyze.py --dir {d} --traj 04_prod.dcd --last-ns 50")
    return 0 if rc == 0 else 2


if __name__ == "__main__":
    sys.exit(main())