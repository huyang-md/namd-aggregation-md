"""Scaffold a NAMD/CHARMM-GUI case: write case.json plus the four stage .conf files.

The rendered text is deterministic, so preflight.py can re-render from case.json and
tell you whether a .conf on disk has drifted from the recipe.

    python scaffold.py --dir <system dir> --name mycase
    python scaffold.py --dir ... --dry-run
"""
