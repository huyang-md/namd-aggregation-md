"""Build a correct continuation .conf for an interrupted NAMD run.

Replaces the hand-written checklist:
  1. point at the restart triplet
  2. rename the output so old data is not appended to
  3. set firsttimestep to the real step of the .xsc (not to what you remember)
  4. drop cellBasisVector, the cell comes from the .xsc
and adds the two things the checklist kept missing: a consistency check on the
triplet, and a disk estimate for what is left to run.

    python restart.py --dir <dir> --from prod_final --target-ns 100
    python restart.py --dir <dir> --from 03_prod --target-ns 100 --write
"""
from __future__ import annotations

import argparse
import os
import shutil
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import namdlib  # noqa: E402
import preflight  # noqa: E402

DROP_KEYS = {
    "binCoordinates", "binVelocities", "extendedSystem", "outputName",
    "firsttimestep", "run", "dcdfreq", "restartfreq",
}
CELL_KEYS = {"cellBasisVector1", "cellBasisVector2", "cellBasisVector3", "cellOrigin"}


def _binding(directory, base):
    """Return the restart triplet, accepting both NAMD naming schemes.

    A run that finished writes <name>.coor/.vel/.xsc; a run that was interrupted
    leaves the periodic <name>.restart.coor/.vel/.xsc. Prefer the periodic set
    when both exist, then fall back to the final snapshot.
    """
    out = {}
    for ext in ("coor", "vel", "xsc"):
        for cand in (f"{base}.restart.{ext}", f"{base}.{ext}"):
            p = os.path.join(directory, cand)
            if os.path.exists(p):
                out[ext] = dict(path=p, name=os.path.basename(p),
                                size=os.path.getsize(p), mtime=os.path.getmtime(p))
                break
    return out


def _find_conf_with_output(directory, from_name):
    """Find the .conf whose outputName is from_name; fall back to prod confs."""
    candidates = []
    for f in sorted(os.listdir(directory)):
        if not f.endswith(".conf"):
            continue
        p = os.path.join(directory, f)
        try:
            with open(p, "r", errors="replace") as fh:
                for line in fh:
                    s = line.split("#", 1)[0].split()
                    if len(s) >= 2 and s[0] == "outputName" and s[1].strip('"') == from_name:
                        return p
        except OSError:
            continue
        candidates.append(p)
    for pref in ("04_prod.conf", "product.conf"):
        p = os.path.join(directory, pref)
        if os.path.exists(p):
            return p
    return candidates[0] if candidates else None


def patch_conf(text, values, cell_commented=None, drop_extra=()):
    """Rewrite a NAMD conf: drop managed keys, comment cell keys, insert values."""
    lines = text.replace("\r\n", "\n").split("\n")
    drop = DROP_KEYS | set(drop_extra)
    kept, commented = [], []
    for line in lines:
        stripped = line.split("#", 1)[0].strip()
        key = stripped.split()[0] if stripped else ""
        if key in drop:
            continue
        if key in CELL_KEYS:
            commented.append(("# " + line.strip()) if not line.lstrip().startswith("#") else line)
            continue
        kept.append(line)

    insert_at = 0
    for i, line in enumerate(kept):
        if line.split("#", 1)[0].strip().startswith("coordinates"):
            insert_at = i + 1
            break

    block = ["", "# === Restart (generated by restart.py) ==="]
    block += [f"{k:<18} {v}" for k, v in values["head"]]
    if cell_commented:
        block += ["# cellBasisVector/cellOrigin removed: the cell comes from the .xsc"]
        block += commented
    block += ["", "# === Run (generated) ==="]
    block += [f"{k:<18} {v}" for k, v in values["tail"]]
    block.append("")

    out = kept[:insert_at] + block + kept[insert_at:]
    return "\n".join(out)


def parse_args(argv=None):
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--dir", required=True)
    p.add_argument("--from", dest="from_name", required=True,
                   help="outputName of the interrupted run, e.g. prod_final (looks for <from>.restart.*)")
    p.add_argument("--target-ns", type=float, required=True, help="total run length to reach, in ns")
    p.add_argument("--new-name", help="outputName for the continuation")
    p.add_argument("--part-ns", type=float, default=0.0,
                   help="only submit this many ns now (for queue time limits); 0 = all remaining")
    p.add_argument("--dcdfreq-ps", type=float, help="frame interval for the continuation")
    p.add_argument("--scaling", type=float,
                   help="force oneFourScaling to this value (e.g. 1.0 to undo a typo that "
                        "ran a production stage at 1.07)")
    p.add_argument("--write", action="store_true", help="write the .conf (default: print only)")
    p.add_argument("--overwrite", action="store_true")
    return p.parse_args(argv)


def main(argv=None):
    a = parse_args(argv)
    d = os.path.abspath(a.dir)
    trip = _binding(d, a.from_name)
    missing = [e for e in ("coor", "vel", "xsc") if e not in trip]
    if missing:
        sys.exit(f"missing restart file(s) {', '.join(missing)} for '{a.from_name}' "
                 f"in {d}\nlooked for {a.from_name}.restart.<ext> and {a.from_name}.<ext>")

    xsc = namdlib.read_xsc(trip["xsc"]["path"])
    step = xsc["step"]

    ts_fs = 2.0
    src = _find_conf_with_output(d, a.from_name)
    if not src:
        sys.exit(f"no .conf found in {d} to base the continuation on; "
                 "run scaffold.py first")
    conf, _ = preflight.parse_conf(src)
    if conf.get("timestep"):
        ts_fs = float(conf["timestep"])
    dcdfreq_ps = a.dcdfreq_ps
    if dcdfreq_ps is None:
        if conf.get("dcdfreq") and conf.get("timestep"):
            dcdfreq_ps = float(conf["dcdfreq"]) * float(conf["timestep"]) / 1000.0
        else:
            dcdfreq_ps = 10.0
    dt_ps = ts_fs / 1000.0
    dcdfreq_steps = max(1, int(round(dcdfreq_ps / dt_ps)))

    target_steps = int(round(a.target_ns * 1000.0 / dt_ps))
    remaining = target_steps - step
    part_steps = int(round(a.part_ns * 1000.0 / dt_ps)) if a.part_ns else 0
    run_steps = min(remaining, part_steps) if part_steps else remaining

    new_name = a.new_name or f"{a.from_name}_cont"
    natoms = None
    psf = conf.get("structure")
    if psf and os.path.exists(os.path.join(d, psf)):
        natoms, _ = namdlib.read_psf(os.path.join(d, psf))

    print(f"directory : {d}")
    print(f"from      : {a.from_name}.restart.{{coor,vel,xsc}}")
    print(f"step      : {step:,}  ({step * dt_ps / 1000.0:.2f} ns)")
    print(f"target    : {target_steps:,} steps ({a.target_ns:.2f} ns)")
    print(f"remaining : {remaining:,} steps ({remaining * dt_ps / 1000.0:.2f} ns)")
    print(f"source    : {os.path.basename(src) if src else '(none)'}")
    print(f"new name  : {new_name}")

    # --- triplet consistency -------------------------------------------------
    # Only a .coor/.vel OLDER than the .xsc is suspicious: NAMD writes the extended
    # system first, so a crash leaves the geometry from an earlier step. A newer
    # timestamp just means the file was copied or re-written later.
    stale = [k for k in ("coor", "vel") if trip[k]["mtime"] < trip["xsc"]["mtime"] - 120]
    if stale:
        print(f"\n[warn] {', '.join(stale)} older than {trip['xsc']['name']}:")
        for k in ("coor", "vel", "xsc"):
            print(f"         {trip[k]['name']:<26} "
                  f"{time.strftime('%Y-%m-%d %H:%M:%S', time.localtime(trip[k]['mtime']))}")
        print("       NAMD writes .xsc before .coor/.vel, so a crash can leave geometry from")
        print(f"       an older step. firsttimestep will be {step} from the .xsc; if the")
        print("       coordinates are from an earlier step the run starts from the wrong")
        print("       geometry. Prefer a triplet written together.")
    else:
        delta = max(mt := [trip[k]["mtime"] for k in ("coor", "vel", "xsc")]) - min(mt)
        print(f"\n[ok] restart triplet consistent (spread {delta / 60:.1f} min, "
              ".coor/.vel not older than .xsc)")

    if remaining <= 0:
        sys.exit("\nnothing to run: the target length is already reached.")

    if natoms:
        need = run_steps / dcdfreq_steps * namdlib.frame_bytes_for(natoms)
        free = shutil.disk_usage(d).free
        print(f"disk      : ~{namdlib.human_bytes(need)} for {run_steps / dcdfreq_steps:,.0f} frames, "
              f"free {namdlib.human_bytes(free)}")
        if need > free * 0.9:
            print("[warn] not enough free space; reduce --part-ns or clean old trajectories")

    head = [
        ("binCoordinates", os.path.basename(trip["coor"]["path"])),
        ("binVelocities", os.path.basename(trip["vel"]["path"])),
        ("extendedSystem", os.path.basename(trip["xsc"]["path"])),
        ("outputName", new_name),
        ("firsttimestep", str(step)),
    ]
    tail = [
        ("dcdfreq", str(dcdfreq_steps)),
        ("restartfreq", str(dcdfreq_steps)),
        ("run", str(run_steps)),
    ]

    drop_extra = ()
    scale_note = ""
    if a.scaling is not None:
        src_scaling = conf.get("oneFourScaling")
        if src_scaling is not None and abs(float(src_scaling) - a.scaling) > 1e-9:
            print(f"\n[warn] {os.path.basename(src)} ran with oneFourScaling {float(src_scaling):g}")
            print(f"       the continuation forces {a.scaling:g}; this changes the potential, "
                  "so do not splice the two trajectories without saying so")
            scale_note = (f"# oneFourScaling forced to {a.scaling:g} "
                          f"(was {float(src_scaling):g})\n")
        drop_extra = ("oneFourScaling", "1-4scaling")
        tail.append(("oneFourScaling", f"{float(a.scaling)}"))

    base_text = open(src, encoding="utf-8", errors="replace").read() if src else ""
    header = (
        "#############################################################\n"
        f"# continuation of {a.from_name}, generated by restart.py\n"
        f"# step {step:,} -> {step + run_steps:,} of {target_steps:,} "
        f"({run_steps * dt_ps / 1000.0:.2f} ns now)\n"
        + scale_note +
        "#############################################################\n"
    )
    text = header + patch_conf(base_text, {"head": head, "tail": tail},
                               cell_commented=True, drop_extra=drop_extra)

    out_path = os.path.join(d, new_name + ".conf")
    print()
    if a.write:
        if os.path.exists(out_path) and not a.overwrite:
            sys.exit(f"{out_path} exists; pass --overwrite or --new-name")
        with open(out_path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        print(f"wrote {out_path}")
        print(f"run it with: namd2 {new_name}.conf > {new_name}.log")
    else:
        print("---- preview (use --write to save) ----")
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
